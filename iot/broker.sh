#!/usr/bin/env bash
# MQTT broker (Eclipse Mosquitto) for SignTalk, run as a normal user - no sudo needed.
#   iot/broker.sh start | stop | status | restart | test
# Uses the system mosquitto if it is installed (sudo apt install mosquitto mosquitto-clients),
# otherwise the copy unpacked in iot/broker/ (see iot/README.md, "Broker without sudo").
# Login: user "signtalk", password "12345678" (change with: iot/broker.sh passwd NEWPASS)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PORT="${MQTT_PORT:-1883}"
USER_NAME="${MQTT_USER:-signtalk}"
PASS="${MQTT_PASS:-12345678}"
PID="$HERE/data/mosquitto.pid"
LOG="$HERE/data/mosquitto.log"
LOCAL="$HERE/broker"
mkdir -p "$HERE/data"

if command -v mosquitto >/dev/null 2>&1; then
  MOSQ=mosquitto; PUB=mosquitto_pub; SUB=mosquitto_sub; PW=mosquitto_passwd
else
  export LD_LIBRARY_PATH="$LOCAL/usr/lib/aarch64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  MOSQ="$LOCAL/usr/sbin/mosquitto"; PUB="$LOCAL/usr/bin/mosquitto_pub"; SUB="$LOCAL/usr/bin/mosquitto_sub"; PW="$LOCAL/usr/bin/mosquitto_passwd"
fi

write_conf() {
  "$PW" -c -b "$HERE/data/passwd" "$USER_NAME" "$PASS" >/dev/null 2>&1
  chmod 600 "$HERE/data/passwd"
  cat > "$HERE/data/mosquitto.conf" <<CONF
# generated by iot/broker.sh - do not edit, change the script instead
listener $PORT 0.0.0.0
allow_anonymous false
password_file $HERE/data/passwd
persistence true
persistence_location $HERE/data/
log_dest file $LOG
log_type error
log_type warning
log_type notice
connection_messages true
CONF
}

running() { [ -f "$PID" ] && kill -0 "$(cat "$PID")" 2>/dev/null; }

case "${1:-status}" in
  start)
    if running; then echo "broker already running (pid $(cat "$PID"))"; exit 0; fi
    write_conf
    nohup "$MOSQ" -c "$HERE/data/mosquitto.conf" >/dev/null 2>&1 &
    echo $! > "$PID"; sleep 1
    if running; then echo "MQTT broker started on port $PORT (pid $(cat "$PID"))"; else echo "broker failed to start, see $LOG"; tail -5 "$LOG" 2>/dev/null; exit 1; fi ;;
  stop)
    if running; then kill "$(cat "$PID")"; rm -f "$PID"; echo "broker stopped"; else echo "broker is not running"; fi ;;
  restart) "$0" stop; sleep 1; "$0" start ;;
  status)
    if running; then echo "broker running (pid $(cat "$PID")) on port $PORT"; else echo "broker is not running"; exit 1; fi ;;
  passwd)
    [ $# -ge 2 ] || { echo "usage: broker.sh passwd NEWPASSWORD"; exit 1; }
    echo "set MQTT_PASS=$2 when starting the broker, the server, the bridge and in the ESP32 sketch"; ;;
  test)   # publish one message and read it back
    "$SUB" -h 127.0.0.1 -p "$PORT" -u "$USER_NAME" -P "$PASS" -t 'signtalk/selftest' -C 1 -W 5 &
    sleep 1; "$PUB" -h 127.0.0.1 -p "$PORT" -u "$USER_NAME" -P "$PASS" -t 'signtalk/selftest' -m 'broker works'; wait ;;
  *) echo "usage: $0 start|stop|restart|status|test"; exit 1 ;;
esac
